const [lib, executablePath, output, url, exchange, first, second] = process.argv.slice(2);
const {chromium}=require(lib);
const assert=require('node:assert/strict');
const path=require('node:path');

(async()=>{
  const browser=await chromium.launch(executablePath?{executablePath}:{});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:900}});
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    const shot=async name=>{await page.locator('#toast').waitFor({state:'hidden'});await page.screenshot({path:path.join(output,name+'.png')})};
    await page.goto(url);
    await page.locator('[data-view=todos]').click();
    await page.locator('#todo-input-toggle').click();
    await page.locator('#todo-raw-form textarea').fill('明天向供应商确认样品报价');
    await page.getByRole('button',{name:'保存原文'}).click();
    await page.locator('[data-normalize]').waitFor();
    await shot('01-natural-intake');
    await page.locator('[data-normalize]').click();
    await page.locator('[data-withdraw-todo]').waitFor();
    await shot('01b-workbuddy-queue');
    const jid=await page.locator('[data-withdraw-todo]').getAttribute('data-withdraw-todo');
    const fs=require('node:fs');
    const job=JSON.parse(fs.readFileSync(path.join(exchange,'inputs',jid+'.json'),'utf8'));
    const outputJson=Object.fromEntries(['schema_version','workspace_id','workspace_epoch','job_id','input_sha256'].map(k=>[k,job[k]]));
    const source=job.context.sources[0];
    outputJson.decisions=[{source_id:source.id,actions:[{kind:'new',target:'',title:'确认样品报价',
      note:'跟进供应商的样品报价。',quote:source.raw,status:''}]}];
    fs.writeFileSync(path.join(exchange,'outputs',jid+'.json'),JSON.stringify(outputJson));
    await page.locator('[data-view=settings]').click();
    await page.locator('#consume-results').click();
    await page.waitForFunction(()=>document.querySelector('#toast')?.textContent.includes('已读取'));
    await page.locator('#draft-ai-settings [name=mode]').selectOption('api');
    await page.getByRole('button',{name:'保存 AI 设置'}).click();
    await page.getByText('AI 设置已保存',{exact:true}).waitFor();
    await page.locator('[data-view=todos]').click();
    await page.locator('#todo-list [data-todo]').waitFor();
    await page.locator('#todo-mail-toggle').click();
    await page.locator('[data-scope-mail="'+second+'"]').uncheck();
    await page.locator('#run-mail-todos').click();
    await page.getByRole('button',{name:'确认合并'}).waitFor();
    assert.equal(await page.locator('#todo-list').isVisible(),false);
    const choice=page.getByRole('radio');
    assert.ok(await choice.first().isChecked());
    await choice.last().check();
    await choice.first().check();
    const independent=page.locator('.separate-action');
    await independent.locator('summary').focus();
    await page.keyboard.press('Enter');
    assert.ok(await independent.getByRole('button',{name:'确认创建'}).isVisible());
    await page.keyboard.press('Enter');
    await page.getByRole('heading',{name:'核对重复事项'}).click();
    await shot('02-duplicate-review');
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await shot('02-mobile-review');
    await page.setViewportSize({width:1440,height:900});
    await page.getByRole('button',{name:'确认合并'}).click();
    await page.locator('[data-proposal]').waitFor({state:'detached'});
    await page.locator('#todo-mail-toggle').click();
    await page.locator('[data-scope-mail="'+second+'"]').waitFor();
    assert.equal(await page.locator('[data-scope-mail="'+first+'"]').count(),0);
    await page.locator('#run-mail-todos').click();
    await page.locator('#todo-list .badge.waiting').waitFor();
    await shot('02b-worklist');
    await page.locator('#todo-list [data-todo]').click();
    await page.locator('[data-todo-detail-tab=progress]').click();
    await page.locator('[data-log-mail]').waitFor();
    await shot('03-status-progress');
    await page.locator('[data-log-mail]').click();
    await page.getByRole('heading',{name:/相关会话/}).waitFor();
    await page.keyboard.press('Escape');
    await page.locator('#todo-list [data-todo]').click();
    await page.locator('[data-todo-detail-tab=source]').click();
    await page.getByText('合并保留的原文',{exact:true}).waitFor();
    await shot('04-sources');
    await page.keyboard.press('Escape');
    await page.setViewportSize({width:390,height:844});
    await page.locator('#todo-input-toggle').click();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.keyboard.press('Escape');
    assert.ok(await page.locator('#todo-input-toggle').evaluate(el=>document.activeElement===el));
    for(const text of ['确认设计进度','复核收货日期']){
      await page.locator('#todo-input-toggle').click();
      await page.locator('#todo-raw-form textarea').fill(text);
      await page.getByRole('button',{name:'保存原文'}).click();
      await page.locator('.review-sheet:visible blockquote').filter({hasText:text}).waitFor();
    }
    await page.getByRole('button',{name:/自然语言录入 确认设计进度/}).click();
    assert.equal(await page.locator('.review-sheet:visible blockquote').innerText(),'确认设计进度');
    assert.equal(await page.locator('.review-sheet:visible').count(),1);
    await page.locator('[data-todo-lane=review]').focus();
    await page.keyboard.press('ArrowLeft');
    await page.locator('#todo-status-filter').selectOption('done');
    await page.getByText('暂无符合条件的事项').waitFor();
    await page.locator('#todo-status-filter').selectOption('waiting');
    await page.locator('#todo-list .badge.waiting').waitFor();
    assert.deepEqual(errors,[]);
    console.log('PASS: natural input, relative deadline, per-mail selection, duplicate review and merge, follow-up state, evidence timeline, original mail, retained sources, narrow layout');
  } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
